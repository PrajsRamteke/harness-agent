#!/usr/bin/env python3
"""Regenerate jarvis/web/static/js/brands.data.js — the brand logos Jarvis web shows.

Sources, in order: Lobe Icons (MIT, github.com/lobehub/lobe-icons) for AI tools
and providers, then Simple Icons (CC0, simpleicons.org) for everything else
(Slack, Stripe, GitLab, JetBrains …), both single-colour `currentColor` sets, so a
logo follows the theme and the tile's tint. VS Code is in neither; it is SVGL's
(github.com/pheralb/svgl) silhouette. Logos stay the property of their owners.

Run:  python3 scripts/gen_brand_icons.py   (needs internet; the result is committed,
so Jarvis web still draws every logo offline on the LAN.)
Add a logo: put its Lobe slug in LOBE below; map any odd name to it in brands.js's ALIAS.
"""
from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

LOBE_RAW = "https://raw.githubusercontent.com/lobehub/lobe-icons/master/packages/static-svg/icons/{}.svg"
OUT = Path(__file__).resolve().parent.parent / "jarvis" / "web" / "static" / "js" / "brands.data.js"

LOBE = [
    # Coding agents and editors
    "claude", "claudecode", "anthropic", "codex", "openai", "antigravity", "gemini", "geminicli",
    "cursor", "windsurf", "kiro", "github", "githubcopilot", "cline", "mcp",
    # Providers
    "google", "openrouter", "opencode", "ollama", "lmstudio", "deepseek", "kimi", "moonshot",
    "qwen", "mistral", "groq", "xai", "together", "fireworks", "zai", "zhipu", "cerebras",
    "deepinfra", "minimax", "nvidia", "perplexity", "cohere", "huggingface", "meta", "azure",
    "bedrock", "aws", "vercel", "cloudflare", "vllm", "openwebui", "sambanova", "nebius",
    "xiaomimimo", "siliconcloud", "novita", "replicate", "modelscope", "stepfun", "doubao",
    "bytedance", "alibaba", "baidu", "gemma", "grok",
    # MCP marketplace
    "figma", "notion", "exa", "tavily",
]

# Simple Icons slugs: the MCP marketplace, editors and local-model servers Lobe doesn't draw.
SIMPLE = [
    "slack", "intercom", "linear", "atlassian", "clickup", "asana", "todoist", "airtable", "miro",
    "dropbox", "gitlab", "sentry", "postman", "buildkite", "grafana", "webflow", "wix",
    "cloudinary", "supabase", "netlify", "neon", "prisma", "render", "stripe", "paypal", "square",
    "posthog", "mixpanel", "brave", "git", "canva", "playwright", "googlechrome", "docker",
    "jetbrains", "zedindustries", "xcode", "zapier", "railway",
]
SIMPLE_RAW = "https://cdn.jsdelivr.net/npm/simple-icons@latest/icons/{}.svg"

# Not in Lobe Icons: SVGL's VS Code silhouette (100x100 box), scaled into the 24x24 box.
VSCODE = (
    '<g transform="scale(.24)"><path d="M70.912 99.317a6.223 6.223 0 0 0 4.96-.19l20.589-9.907A6.25 6.25 0 0 0 100 83.587V16.413'
    'a6.25 6.25 0 0 0-3.54-5.632L75.874.874a6.226 6.226 0 0 0-7.104 1.21L29.355 38.04 12.187 25.01a4.162 '
    '4.162 0 0 0-5.318.236l-5.506 5.009a4.168 4.168 0 0 0-.004 6.162L16.247 50 1.36 63.583a4.168 4.168 0 '
    '0 0 .004 6.162l5.506 5.01a4.162 4.162 0 0 0 5.318.236l17.168-13.032L68.77 97.917a6.217 6.217 0 0 0 '
    '2.143 1.4ZM75.015 27.3 45.11 50l29.906 22.701V27.3Z" fill-rule="evenodd" clip-rule="evenodd"/></g>'
)


def fetch(slug: str, raw: str = LOBE_RAW) -> str | None:
    try:
        with urllib.request.urlopen(raw.format(slug), timeout=20) as r:
            return r.read().decode()
    except Exception as e:  # noqa: BLE001 - report and skip
        print(f"skip {slug}: {e}", file=sys.stderr)
        return None


def inner(svg: str) -> str | None:
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not m:
        return None
    body = re.sub(r"<title>.*?</title>", "", m.group(1), flags=re.S).strip()
    # Ids (masks, gradients, clips) would collide once several logos share one page.
    if "id=" in body or "url(#" in body:
        return None
    return body.replace("></path>", "/>")


def main() -> None:
    icons: dict[str, str] = {}
    for slug in LOBE:
        raw = fetch(slug)
        body = inner(raw) if raw else None
        if body is None:
            print(f"skip {slug}: not a plain single-colour mark", file=sys.stderr)
            continue
        icons[slug] = body
    for slug in SIMPLE:
        if slug in icons:  # Lobe's mark wins
            continue
        raw = fetch(slug, SIMPLE_RAW)
        body = inner(raw) if raw else None
        if body is None:
            print(f"skip {slug}: not a plain single-colour mark", file=sys.stderr)
            continue
        icons[slug] = body
    icons["vscode"] = VSCODE
    data = json.dumps(icons, separators=(",", ":"), sort_keys=True)
    OUT.write_text(
        "/** Brand logo shapes (24x24, currentColor) — Lobe Icons (MIT) + SVGL's VS Code.\n"
        " * Generated by scripts/gen_brand_icons.py; do not edit by hand. Use brands.js. */\n"
        f"const BRANDS = {data};\n"
        "export const BRAND_SLUGS = new Set(Object.keys(BRANDS));\n"
        "export function brandBody(slug) { return BRANDS[slug] || ''; }\n"
    )
    print(f"wrote {len(icons)} logos to {OUT}")


if __name__ == "__main__":
    main()
